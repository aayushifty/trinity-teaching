#!/usr/bin/env node
// Adds extra IOE / IOM practice questions (server/bank/*.jsonl) to the question bank, without
// touching the existing bank. Safe to run again: questions already in the bank are skipped.
//
//   node scripts/add-bank.mjs bank/*.jsonl > extra.sql
//   npx wrangler d1 execute trinity-ai --remote --file=extra.sql
//
// Each line: {"exam","subject","grade","topic","question","options":[4],"answer","explanation","difficulty"}
// Every item goes in with verified = 0, so the server's background check re-solves it before any
// class sees it; items the check disagrees with are held back (verified -1 / -2).
import fs from 'node:fs';

const SUBJECT_EXAMS = { physics: ['IOE', 'IOM'], chemistry: ['IOE', 'IOM'], biology: ['IOM'], mathematics: ['IOE'], english: ['IOE'] };
// Not "Question bank%": import-bank.mjs deletes those when it re-imports, these stay.
const SOURCE = { IOE: 'Extra bank (IOE)', IOM: 'Extra bank (IOM)' };

function invalid(r) {
  if (!r || typeof r !== 'object') return 'not an object';
  if (!SUBJECT_EXAMS[r.subject]) return `unknown subject ${r.subject}`;
  if (!SUBJECT_EXAMS[r.subject].includes(r.exam)) return `${r.exam} does not test ${r.subject}`;
  if (!['11', '12'].includes(String(r.grade))) return 'grade must be 11 or 12';
  if (typeof r.question !== 'string' || r.question.trim().length < 10) return 'question missing';
  if (!Array.isArray(r.options) || r.options.length !== 4 || r.options.some((o) => typeof o !== 'string' || !o.trim())) return 'need 4 options';
  if (new Set(r.options.map((o) => o.trim().toLowerCase())).size !== 4) return 'options repeat';
  if (!['A', 'B', 'C', 'D'].includes(r.answer)) return 'answer must be A-D';
  return null;
}

const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const files = process.argv.slice(2);
if (!files.length) { console.error('usage: add-bank.mjs <file.jsonl> ... > out.sql'); process.exit(1); }
const rows = [];
const seen = new Set();
let bad = 0;
for (const f of files) {
  fs.readFileSync(f, 'utf8').split(/\r?\n/).forEach((line, i) => {
    if (!line.trim()) return;
    let r;
    try { r = JSON.parse(line); } catch { console.error(`${f}:${i + 1} not JSON`); bad++; return; }
    const why = invalid(r);
    if (why) { console.error(`${f}:${i + 1} ${why}`); bad++; return; }
    const key = `${r.subject}|${r.question.trim().toLowerCase()}`;
    if (seen.has(key)) { console.error(`${f}:${i + 1} duplicate`); bad++; return; }
    seen.add(key);
    rows.push(r);
  });
}

const out = ['-- Generated by scripts/add-bank.mjs. Adds extra practice questions; skips any already in the bank.'];
for (const exam of new Set(rows.map((r) => r.exam))) {
  out.push(`INSERT INTO papers (exam, year, source) SELECT ${q(exam)}, NULL, ${q(SOURCE[exam])} WHERE NOT EXISTS (SELECT 1 FROM papers WHERE source = ${q(SOURCE[exam])});`);
}
for (const r of rows) {
  const question = r.question.trim();
  out.push('INSERT INTO questions (paper_id, exam, year, qno, subject, portion, topic, question, options, answer, answer_source, difficulty, grade, origin, explanation, verified) '
    + `SELECT (SELECT id FROM papers WHERE source = ${q(SOURCE[r.exam])}), ${q(r.exam)}, NULL, NULL, ${q(r.subject)}, NULL, ${q(r.topic || null)}, ${q(question)}, `
    + `${q(JSON.stringify(r.options.map((o) => o.trim())))}, ${q(r.answer)}, 'bank', ${Math.min(5, Math.max(1, Number(r.difficulty) || 3))}, ${q(String(r.grade))}, 'bank', ${q(r.explanation || null)}, 0 `
    + `WHERE NOT EXISTS (SELECT 1 FROM questions WHERE subject = ${q(r.subject)} AND question = ${q(question)});`);
}
process.stdout.write(`${out.join('\n')}\n`);
console.error(`${rows.length} questions written, ${bad} rejected`);
if (bad) process.exitCode = 1;
